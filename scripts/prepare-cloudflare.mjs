import { copyFile, open, readdir, readFile, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'

// Turns the build in dist into a Cloudflare Workers static assets upload: adds
// the _headers and _redirects files that replace nginx.conf, and splits files
// over the 25 MiB per-asset limit into parts that cloudflare/worker.js joins.
const outDir = path.resolve('dist')
const MAX_ASSET_BYTES = 25 * 1024 * 1024
// Each pattern must also be listed in assets.run_worker_first in wrangler.jsonc.
const SPLIT_FILES = [/^assets\/typst_ts_web_compiler_bg-[\w-]+\.wasm$/]

// Share the response headers with nginx so the two deployments cannot drift.
const headers = []
for (const line of (await readFile('nginx-security-headers.conf', 'utf8')).split('\n')) {
  const directive = line.trim()
  if (!directive || directive.startsWith('#')) continue
  const match = directive.match(/^add_header\s+([\w-]+)\s+(?:"([^"]*)"|(\S+))\s+always;$/)
  if (!match) throw new Error(`Cannot convert this nginx directive to _headers: ${directive}`)
  headers.push(`  ${match[1]}: ${match[2] ?? match[3]}`)
}

await writeFile(path.join(outDir, '_headers'), `# Generated by scripts/prepare-cloudflare.mjs from nginx-security-headers.conf and nginx.conf.
/*
${headers.join('\n')}
  Cache-Control: no-cache

# Vite fingerprints these file names, so their content never changes.
/assets/*
  ! Cache-Control
  Cache-Control: public, max-age=31536000, immutable

# Show the model card and notices as text instead of downloading them.
/*.md
  ! Content-Type
  Content-Type: text/plain; charset=utf-8
`)
await copyFile('cloudflare/_redirects', path.join(outDir, '_redirects'))

const files = (await readdir(outDir, { recursive: true, withFileTypes: true }))
  .filter((entry) => entry.isFile())
  .map((entry) => path.join(entry.parentPath, entry.name))

let split = 0
for (const file of files) {
  const relativePath = path.relative(outDir, file).split(path.sep).join('/')
  if (/\.(part\d+|parts\.json)$/.test(relativePath)) throw new Error(`${relativePath} is from an earlier split; build from a clean dist.`)
  const handle = await open(file)
  try {
    const { size } = await handle.stat()
    if (size <= MAX_ASSET_BYTES) continue
    if (!SPLIT_FILES.some((pattern) => pattern.test(relativePath))) {
      throw new Error(`${relativePath} exceeds the 25 MiB Cloudflare asset limit. Add it to SPLIT_FILES and run_worker_first.`)
    }
    const count = Math.ceil(size / MAX_ASSET_BYTES)
    const partBytes = Math.ceil(size / count)
    const sizes = []
    for (let index = 0, position = 0; position < size; index++, position += partBytes) {
      const buffer = Buffer.alloc(Math.min(partBytes, size - position))
      await handle.read(buffer, 0, buffer.length, position)
      await writeFile(`${file}.part${index}`, buffer)
      sizes.push(buffer.length)
    }
    // The Worker reads the sizes to send a Content-Length before the parts.
    await writeFile(`${file}.parts.json`, JSON.stringify({ sizes }) + '\n')
    console.log(`Split ${relativePath} (${(size / 1024 / 1024).toFixed(1)} MiB) into ${count} parts.`)
    split++
  } finally {
    await handle.close()
  }
  await rm(file)
}
console.log(`Prepared dist for Cloudflare: _headers, _redirects, and ${split} split ${split === 1 ? 'file' : 'files'}.`)
